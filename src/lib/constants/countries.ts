/** Country names alone, alphabetical — for plain select options. */
export const WORLD_COUNTRY_NAMES: string[] = WORLD_COUNTRIES.map((c) => c.country);

const BY_NAME = new Map(WORLD_COUNTRIES.map((c) => [c.country.toLowerCase(), c]));

/** Representative coordinate for a country named in free text. */
export function countryCoordinates(
  country?: string | null,
): { lat: number; lng: number } | null {
  if (!country) return null;
  const hit = BY_NAME.get(country.trim().toLowerCase());
  return hit ? { lat: hit.lat, lng: hit.lng } : null;
}
